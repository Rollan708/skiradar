export const FX_RATES_TO_RUB: Record<'RUB' | 'KZT' | 'EUR' | 'USD', number> = {
  RUB: 1,
  KZT: 0.195, // 1000 KZT ≈ 195 RUB (1 RUB ≈ 5.13 KZT)
  EUR: 104.5, // 1 EUR ≈ 104.5 RUB
  USD: 96.2,  // 1 USD ≈ 96.2 RUB
};

export function convertCurrency(
  amount: number,
  from: 'RUB' | 'KZT' | 'EUR' | 'USD',
  to: 'RUB' | 'KZT' | 'EUR' | 'USD'
): number {
  if (from === to) return Math.round(amount);
  const inRub = amount * (FX_RATES_TO_RUB[from] || 1);
  const out = inRub / (FX_RATES_TO_RUB[to] || 1);
  return to === 'EUR' || to === 'USD' ? Math.round(out) : Math.round(out / 10) * 10;
}

